import type { Nuxt } from '@nuxt/schema'

import type { ShopifyConfig } from '../types'

import { addTemplate } from '@nuxt/kit'
import { relative } from 'pathe'

import { ShopifyClientType } from '../schemas'
import { DOCUMENT_ROUTING_ORDER, getConfiguredClients, splitDocuments } from '../utils/clients'
import { getIntrospectionFilename } from '../utils/templates'
import { useLogger } from '../utils/log'

type GraphqlProject = {
  schema: string
  documents: string[]
  exclude: string[]
}

export default function setupGraphqlConfig(nuxt: Nuxt, config: ShopifyConfig) {
  const logger = useLogger()

  if (!config.graphql.generateConfig) {
    logger.debug('Skipping `graphql.config.mjs` generation: `graphql.generateConfig` is disabled')
    return
  }

  const configured = getConfiguredClients(config)
  const buildDir = relative(nuxt.options.rootDir, nuxt.options.buildDir) || '.nuxt'

  const projects: Record<string, GraphqlProject> = {}

  for (const clientType of DOCUMENT_ROUTING_ORDER) {
    if (!configured.includes(clientType)) continue

    const clientConfig = config.clients[clientType]

    if (!clientConfig || !clientConfig.codegen) continue

    const name = clientType === ShopifyClientType.Storefront ? 'default' : clientType
    const { include, exclude } = splitDocuments(clientConfig.documents ?? [])

    projects[name] = {
      schema: `${buildDir}/${getIntrospectionFilename(clientType, clientConfig.apiVersion)}`,
      documents: include,
      exclude,
    }
  }

  if (!Object.keys(projects).length) {
    logger.debug('Skipping `graphql.config.mjs` generation: no clients with code generation enabled')
    return
  }

  logger.debug(`Generating \`graphql.config.mjs\` with projects: ${Object.keys(projects).join(', ')}`)

  addTemplate({
    filename: 'graphql.config.mjs',
    write: true,
    getContents: () =>
      '// Generated by @nuxtjs/shopify\n'
      + `export const projects = ${JSON.stringify(projects, null, 2)}\n\n`
      + 'export default { projects }\n',
  })
}
